// Writes THIRD_PARTY_NOTICES.md (everything the app ships) and vscode/THIRD_PARTY_NOTICES.md (the
// same minus the D2 compiler, which the extension does not include), with each package's licence text.
//   node scripts/notices.mjs           write both files
//   node scripts/notices.mjs --check   exit 1 if they are out of date
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const NOT_IN_EXTENSION = ['@terrastruct/d2'];

/** Runtime packages (no dev tools), sorted by name. */
export function runtimePackages() {
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  const r = spawnSync(npm, ['ls', '--omit=dev', '--all', '--json'], { cwd: root, encoding: 'utf8', shell: process.platform === 'win32' });
  const seen = new Map();
  const walk = (deps = {}) => {
    for (const [name, info] of Object.entries(deps)) {
      if (!seen.has(name)) seen.set(name, info.version);
      walk(info.dependencies);
    }
  };
  walk(JSON.parse(r.stdout).dependencies);
  return [...seen].map(([name, version]) => ({ name, version })).sort((a, b) => a.name.localeCompare(b.name));
}

function licenceOf(name) {
  const dir = join(root, 'node_modules', name);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  return {
    licence: pkg.license ?? 'see licence text',
    source: (repo ?? pkg.homepage ?? `https://www.npmjs.com/package/${name}`).replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://'),
    text: file ? readFileSync(join(dir, file), 'utf8').trim() : null,
  };
}

export function noticesText(packages, title) {
  const out = [
    `# Third-party notices — ${title}`,
    '',
    'Archi3D is licensed under the MIT License (see LICENSE). It includes the following',
    'third-party software, each under its own licence. Generated by `scripts/notices.mjs`.',
    '',
    '| Package | Version | Licence | Source |',
    '|---|---|---|---|',
  ];
  const infos = packages.map((p) => ({ ...p, ...licenceOf(p.name) }));
  for (const p of infos) out.push(`| ${p.name} | ${p.version} | ${p.licence} | ${p.source} |`);
  for (const p of infos) {
    out.push('', '---', '', `## ${p.name} ${p.version} (${p.licence})`, '', `Source: ${p.source}`, '');
    out.push(p.text ? '```text\n' + p.text + '\n```' : `Licence: ${p.licence} — full text at the source above.`);
  }
  return out.join('\n') + '\n';
}

export function expectedNotices() {
  const all = runtimePackages();
  return {
    [join(root, 'THIRD_PARTY_NOTICES.md')]: noticesText(all, 'Archi3D app, standalone file and website'),
    [join(root, 'vscode', 'THIRD_PARTY_NOTICES.md')]: noticesText(all.filter((p) => !NOT_IN_EXTENSION.includes(p.name)), 'Archi3D for VS Code'),
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const files = expectedNotices();
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(([f, text]) => !existsSync(f) || readFileSync(f, 'utf8') !== text);
    for (const [f] of stale) console.error(`out of date: ${f} (run npm run notices)`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [f, text] of Object.entries(files)) writeFileSync(f, text);
  console.log(`wrote ${Object.keys(files).join(', ')}`);
}
