// Seeded random .arch models for scale tests: systems → containers → components, with links
// mostly inside a container, some across containers, a few across systems.

export interface GenOptions {
  seed: number;
  components: number;
  systems?: number;
  containersPerSystem?: number;
}

/** mulberry32: small, fast, deterministic. */
export function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const KINDS = ['service', 'service', 'component', 'component', 'database', 'queue'];

export function generateArch(opts: GenOptions): string {
  const rand = rng(opts.seed);
  const pick = <T>(xs: T[]): T => xs[Math.floor(rand() * xs.length)];
  const systems = opts.systems ?? 8;
  const perSystem = opts.containersPerSystem ?? 6;
  const containers = systems * perSystem;

  // Component ids grouped by [system][container], spread as evenly as possible.
  const groups: string[][][] = [];
  let made = 0;
  for (let s = 0; s < systems; s++) {
    groups.push([]);
    for (let c = 0; c < perSystem; c++) {
      const k = s * perSystem + c;
      const n = Math.floor(((k + 1) * opts.components) / containers) - Math.floor((k * opts.components) / containers);
      groups[s].push(Array.from({ length: n }, (_, i) => `S${s + 1}C${c + 1}N${i + 1}`));
      made += n;
    }
  }

  const lines = [`# Generated by scripts/generate.mjs: seed ${opts.seed}, ${made} components`];
  for (let s = 0; s < systems; s++) {
    lines.push(`system Sys${s + 1} {`);
    for (let c = 0; c < perSystem; c++) {
      lines.push(`  container S${s + 1}C${c + 1} {`);
      for (const id of groups[s][c]) lines.push(`    ${pick(KINDS)} ${id}`);
      lines.push('  }');
    }
    lines.push('}');
  }

  const links = new Set<string>();
  const out: string[] = [];
  for (let s = 0; s < systems; s++) {
    for (let c = 0; c < perSystem; c++) {
      for (const from of groups[s][c]) {
        const count = rand() < 0.85 ? 1 : 2;
        for (let k = 0; k < count; k++) {
          const r = rand();
          const ts = r < 0.92 ? s : Math.floor(rand() * systems);
          const tc = r < 0.75 ? c : Math.floor(rand() * perSystem);
          const pool = groups[ts][tc];
          if (!pool.length) continue;
          const to = pick(pool);
          const key = `${from}>${to}`;
          if (to === from || links.has(key)) continue;
          links.add(key);
          out.push(`${from} ${rand() < 0.15 ? '=>' : '->'} ${to}`);
        }
      }
    }
  }
  lines.push('', ...out, '');
  return lines.join('\n');
}
